# 只在note 字段值内部替换（避免误伤话术正文/规则表/UI 文案）
NOTE_RE = re.compile(r"('note':\s*')([^']*)(')")


def read_text(p):
    with io.open(p, 'r', encoding='utf-8', newline='') as f:
        return f.read()


def write_atomic(p, s):
    tmp = p + '.tmp_write'
    with io.open(tmp, 'w', encoding='utf-8', newline='') as f:
        f.write(s)
    os.replace(tmp, p)


def fix_note(body):
    hits = []
    for a, b in PAIRS:
        if a in body:
            hits.append((a, b))
            body = body.replace(a, b)
    return body, hits


def main():
    p = os.path.join(BASE, TARGET)
    s = read_text(p)
    total = 0
    all_hits = []

    def repl(m):
        nonlocal total
        new, hits = fix_note(m.group(2))
        if hits:
            total += 1
            all_hits.extend(hits)
        return m.group(1) + new + m.group(3)

    s2 = NOTE_RE.sub(repl, s)
    if s2 != s:
        write_atomic(p, s2)
    print(u'[改写] note 字段 %d 条被改写' % total)

    # 复核：note 内是否还有违禁词
    s3 = read_text(p)
    BAN = re.compile(r'券后|活动价|满减|促销|折扣|特价|大促|免税价|免税渠道|离岛|比价')
    left = [m.group(2) for m in NOTE_RE.finditer(s3) if BAN.search(m.group(2))]
    if left:
        print(u'[残留] %d 条 note 仍含违禁词：' % len(left))
        for n in set(left):
            print(u'   -', n)
    else:
        print(u'[PASS] 全部 note 已无违禁价格口径')
    return 0 if not left else 1


if __name__ == '__main__':
    sys.exit(main())
