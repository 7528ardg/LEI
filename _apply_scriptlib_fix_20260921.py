def set_content(sid, new, label=''):
    """按 id 精确替换单条话术的 content 字段。"""
    global src
    pat = re.compile(r"(id: '" + re.escape(sid) + r"', content: ')((?:\\.|[^'\\])*)(')")
    m = pat.search(src)
    if not m:
        skip.append('set_content %s：未定位到' % sid)
        return False
    if m.group(2) == new:
        skip.append('set_content %s：已是目标态' % sid)
        return True
    src = src[:m.start(2)] + new.replace("'", "\\'") + src[m.end(2):]
    done.append('set_content %-26s %s' % (sid, label))
    return True


def swap(old, new, label, expect=None):
    """全文字符串替换，可选命中数断言。
    new 为 list/tuple 时按出现顺序循环取用（用于破除固定重复句）。"""
    global src
    n = src.count(old)
    if n == 0:
        skip.append('swap %s：0 命中（幂等/已修）' % label)
        return 0
    if expect is not None and n != expect:
        skip.append('swap %s：命中 %d 期望 %d —— 跳过' % (label, n, expect))
        return 0
    if isinstance(new, (list, tuple)):
        parts = src.split(old)
        out = parts[0]
        for i, p in enumerate(parts[1:]):
            out += new[i % len(new)] + p
        src = out
    else:
        src = src.replace(old, new)
    done.append('swap %-38s ×%d' % (label, n))
    return n


def sub_all(rx, repl, label, expect=None):
    global src
    n = len(re.findall(rx, src))
    if n == 0:
        skip.append('sub %s：0 命中（幂等/已修）' % label)
        return 0
    if expect is not None and n != expect:
        skip.append('sub %s：命中 %d 期望 %d —— 跳过' % (label, n, expect))
        return 0
    src = re.sub(rx, repl, src)
    done.append('sub  %-38s ×%d' % (label, n))
    return n


def del_entry(sid):
    """删除一整条话术条目（含可选 productId 等尾随字段）。
    注意：条目是「一行一条」，且部分条目带 `, productId: 'xxx'`，
    因此不能用「tags 紧接 }」的精确形状，改用行内非贪婪匹配。"""
    global src
    rx = re.compile(r"\n[ \t]*\{ id: '" + re.escape(sid) + r"', [^\n]*\},?")
    n = len(rx.findall(src))
    if n != 1:
        skip.append('del_entry %s：命中 %d（期望 1）' % (sid, n))
        return False
    src = rx.sub('', src, count=1)
    done.append('del_entry %s' % sid)
    return True


def append_scripts(cat_key, items, label):
    """在指定栏目的 scripts 数组末尾追加。
    修正了历史补丁（_apply_souvenir_20260916.py）的『双逗号』缺陷：
    该补丁无条件前置 ',\\n'，而数组末项本身已带尾逗号，于是产生 `},,`（elision 空洞）。
    这里改为：锚点前一个可打印字符若已是逗号，就不再前置逗号。"""
    global src
    if all(("id: '%s'" % s[0]) in src for s in items):
        skip.append('append %s：已存在（幂等）' % label)
        return False
    i = src.find(cat_key + ': {')
    if i < 0:
        skip.append('append %s：栏目未找到' % label)
        return False
    j = src.find('\n                ]\n            },', i)
    if j < 0:
        skip.append('append %s：数组收尾锚点未找到' % label)
        return False
    k = j - 1
    while k >= 0 and src[k] in ' \t\r\n':
        k -= 1
    lead = '\n' if k >= 0 and src[k] == ',' else ',\n'
    body = lead + ',\n'.join(
        "                    { id: '%s', content: '%s', tags: %s }" % (s[0], s[1], s[2])
        for s in items)
    src = src[:j] + body + src[j:]
    done.append('append %-30s +%d 条' % (label, len(items)))
    return True


