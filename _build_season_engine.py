def js_str(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def js_obj_terms(d):
    lines = []
    for k in sorted(d.keys()):
        lines.append("    %s: [%s]" % (js_str(k), ', '.join(js_str(x) for x in d[k])))
    return "  var OPEN_TERMS = {\n" + ",\n".join(lines) + "\n  };"


def js_obj_fests(d):
    lines = []
    for k in sorted(d.keys()):
        lines.append("    %s: [%s]" % (js_str(k), ', '.join(js_str(x) for x in d[k])))
    return "  var OPEN_FESTS = {\n" + ",\n".join(lines) + "\n  };"


def js_terms(t):
    lines = []
    for y in sorted(t.keys()):
        inner = ', '.join("%s:'%s'" % (js_str(k), v) for k, v in t[y].items())
        lines.append("    '%s': { %s }" % (y, inner))
    return "  var TERMS = {\n" + ",\n".join(lines) + "\n  };"


def js_lunar(l):
    lines = []
    for y in sorted(l.keys()):
        inner = ', '.join("%s:'%s'" % (k, v) for k, v in l[y].items())
        lines.append("    '%s': { %s }" % (y, inner))
    return "  var LUNAR = {\n" + ",\n".join(lines) + "\n  };"


