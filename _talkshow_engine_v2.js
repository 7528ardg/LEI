    if(n > 0){
      for(let i = 0; i < n; i += 4) brand.add(i);            // 0,4,8… → ≈1/4
      if(n > 3) for(let i = 2; i < n; i += 4) tale.add(i);   // 2,6,10… → ≈1/4（与品牌错开）
    }
