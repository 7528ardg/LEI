  function clipSentence(text, max){
    const t = String(text || '').trim();
    if(!t) return '';
    if(t.length <= max) return t;
    let out = '', buf = '';
    for(let i = 0; i < t.length; i++){
      buf += t.charAt(i);
      if('。！？'.indexOf(t.charAt(i)) >= 0){ out += buf; buf = ''; if(out.length >= max) return out; }
    }
    const all = out + buf;
    return all.length > max ? (all.slice(0, max) + '。') : all;
  }
