  // 节气延伸窗口：节气当日及之后 2 天都算"这个节气里"
  var TERM_SPAN = 3;

  function solarTermOf(dt) {
    var y = dt.getFullYear(), key = md(dt), row = TERMS[String(y)];
    if (row) {
      for (var i = 0; i < TERM_ORDER.length; i++) {
        var name = TERM_ORDER[i];
        var start = row[name];
        if (!start) continue;
        var p = start.split('-');
        var sd = new Date(y, parseInt(p[0], 10) - 1, parseInt(p[1], 10));
        var ed = new Date(sd.getTime() + (TERM_SPAN - 1) * 86400000);
        var cur = new Date(dt.getFullYear(), dt.getMonth(), dt.getDate());
        if (cur >= sd && cur <= ed) return name;
      }
      return '';
    }
    var m = dt.getMonth() + 1, d = dt.getDate();
    for (var k in TERM_RANGE) {
      var t = TERM_RANGE[k];
      if (t[0] === m && d >= t[1] && d <= t[2]) return k;
    }
    return '';
  }

  function festOf(dt) {
    var y = dt.getFullYear(), key = md(dt);
    if (GREG_FESTS[key]) return GREG_FESTS[key];
    if (dt.getMonth() === 4 && dt.getDate() === nthWeekday(y, 5, 2, 0)) return 'mothers';
    if (dt.getMonth() === 5 && dt.getDate() === nthWeekday(y, 6, 3, 0)) return 'fathers';
    var lf = LUNAR[String(y)];
    if (lf) {
      for (var k in lf) { if (lf[k] === key) return k; }
    }
    return '';
  }

  /* 匹配当日：统一委托 DateMatch.todayMatch（同日口径的唯一来源）
   * 委托后的差异：认「假期区间」（春节第 3 天也算春节）、覆盖万圣节/感恩节等
   * 本文件词表没有的节日、输出与文本解析同一结构。
   * DateMatch 尚未加载时回退本文件原逻辑，保证任何加载顺序都能用。
   */
  function match(dt) {
    dt = dt || new Date();
    try {
      var DM = (typeof window !== 'undefined') ? window.DateMatch : null;
      if (DM && DM.todayMatch) {
        var m2 = DM.todayMatch(dt);
        if (!m2) return null;
        return {
          kind: (m2.type === 'term') ? 'solar' : 'festival',
          key: m2.key, name: m2.name, type: m2.type, date: m2.start, via: 'DateMatch'
        };
      }
    } catch (e) {}
    var f = festOf(dt);
    if (f) return { kind: 'festival', key: f, name: FEST_NAMES[f] || f };
    var t = solarTermOf(dt);
    if (t) return { kind: 'solar', key: t, name: t };
    return null;
  }

  function timeOfDay(dt) {
    var h = (dt || new Date()).getHours();
    if (h >= 5 && h < 11) return 'morning';
    if (h >= 11 && h < 14) return 'noon';
    if (h >= 14 && h < 18) return 'afternoon';
    return 'evening';
  }
  var TIME_NAMES = { morning: '清晨', noon: '午间', afternoon: '午后', evening: '晚间' };

  function pick(arr) { return arr[Math.floor(Math.random() * arr.length)]; }

  // 取开场白：优先节日，其次节气，最后按时段
  function opening(dt, opts) {
    opts = opts || {};
    dt = dt || new Date();
    if (opts.fest && OPEN_FESTS[opts.fest]) return pick(OPEN_FESTS[opts.fest]);
    if (opts.term && OPEN_TERMS[opts.term]) return pick(OPEN_TERMS[opts.term]);
    var m = match(dt);
    if (m && m.kind === 'festival' && OPEN_FESTS[m.key]) return pick(OPEN_FESTS[m.key]);
    if (m && m.kind === 'solar' && OPEN_TERMS[m.key]) return pick(OPEN_TERMS[m.key]);
    return null;
  }

  function clockText(dt) {
    dt = dt || new Date();
    return pad(dt.getHours()) + ':' + pad(dt.getMinutes());
  }
