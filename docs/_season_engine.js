  function pad(n) { return n < 10 ? '0' + n : '' + n; }
  function md(dt) { return pad(dt.getMonth() + 1) + '-' + pad(dt.getDate()); }

  // 第 n 个星期几：nth=2, dow=0(周日)
  function nthWeekday(y, month, nth, dow) {
    var first = new Date(y, month - 1, 1).getDay();
    return ((dow - first + 7) % 7) + 1 + (nth - 1) * 7;
  }

  // 精确 24 节气（优先查表；超出表范围退回区间估算）
